package org.brts.lowlevel.titlemenu.descriptor;

/**
 * Supported layout types for title menu button arrangement.
 */
public enum LayoutType {

	/**
	 * Simple vertical text list: titles rendered as selectable text buttons, auto-arranged vertically or in columns.
	 */
	TEXT_LIST,

	/**
	 * Grid of animated thumbnails extracted from source media, composited into the background video with text labels.
	 */
	THUMBNAIL_GRID

}
